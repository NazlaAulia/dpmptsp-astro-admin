    deskripsi  TEXT,
    isi        TEXT,
    urutan     INTEGER NOT NULL DEFAULT 0,
    is_active  BOOLEAN NOT NULL DEFAULT TRUE   -- was status tinyint
);

-- RECONSTRUCTED
-- looks rows up by ('info-sec'), so it is UNIQUE and the child table points at
