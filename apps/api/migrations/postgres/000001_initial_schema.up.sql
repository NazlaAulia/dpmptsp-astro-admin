);
CREATE INDEX regulasi_active_urutan_idx ON regulasi (is_active, urutan, tahun DESC);

-- RECONSTRUCTED
CREATE TABLE aplikasi_publik (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama       VARCHAR(255) NOT NULL,
    deskripsi  TEXT,
    url        VARCHAR(500),
    icon       VARCHAR(100),
    target     VARCHAR(20),
    is_active  BOOLEAN NOT NULL DEFAULT TRUE,
    urutan     INTEGER NOT NULL DEFAULT 0
);

-- RECONSTRUCTED
-- parses with JSON.parse. Stored as TEXT and decoded in Go rather than JSONB:
-- it is never queried by JSON path, so JSONB buys nothing and costs the MySQL
-- migration its equivalence.
CREATE TABLE pelayanan_standar (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tab_key    VARCHAR(100) NOT NULL,
    tab_icon   VARCHAR(100),
